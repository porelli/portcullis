#!/usr/bin/env python3
"""The OLM-free install of a medik8s operator (spike-cluster.md Step 3):
its release bundle (bundle.tar.gz, pinned by sha256 in scripts/lib/ha.sh)
as plain manifests, verbatim but for what OLM itself would add:

  - the CRDs and every other object of bundle/manifests/ (Services, the
    manager's ConfigMap, the aggregated ClusterRoles), in <namespace>;
  - the CSV's ServiceAccounts; its clusterPermissions as a ClusterRole +
    ClusterRoleBinding named after the ServiceAccount, its permissions as a
    Role + RoleBinding in <namespace>;
  - the CSV's deployments as Deployments in <namespace>.

The CSV's webhookdefinitions are left out: no admission webhook is
registered (the operators still serve them with a throwaway certificate,
ha_install_fencing). Kustomize (kube/ha/fencing/kustomization.yaml) pins
the images and narrows the RBAC. Usage:

  python3 kube/ha/fencing/from-bundle.py <bundle.tar.gz> <namespace> > <out.yaml>

tests/k8s_hardening.py check_fencing runs it again and compares.
"""
import io
import sys
import tarfile

import yaml


def main(path, ns):
    docs, csv = [], None
    with tarfile.open(path) as t:
        names = sorted(m.name for m in t.getmembers() if m.isfile() and "/manifests/" in m.name and m.name.endswith(".yaml"))
        for n in names:
            d = yaml.safe_load(io.TextIOWrapper(t.extractfile(n), encoding="utf-8"))
            if d.get("kind") == "ClusterServiceVersion":
                csv = d
            else:
                docs.append(d)
    if csv is None:
        sys.exit(f"{path}: no ClusterServiceVersion")
    for d in docs:
        if d["kind"] not in ("CustomResourceDefinition", "ClusterRole", "ClusterRoleBinding"):
            d.setdefault("metadata", {})["namespace"] = ns
    spec = csv["spec"]["install"]["spec"]
    out = [d for d in docs if d["kind"] == "CustomResourceDefinition"]
    out += [d for d in docs if d["kind"] != "CustomResourceDefinition"]
    sas = sorted({p["serviceAccountName"] for p in spec.get("clusterPermissions", []) + spec.get("permissions", [])})
    for sa in sas:
        out.append({"apiVersion": "v1", "kind": "ServiceAccount", "metadata": {"name": sa, "namespace": ns}})
    for p in spec.get("clusterPermissions", []):
        sa = p["serviceAccountName"]
        out.append({"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "ClusterRole", "metadata": {"name": sa}, "rules": p["rules"]})
        out.append({"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "ClusterRoleBinding", "metadata": {"name": sa},
                    "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "ClusterRole", "name": sa},
                    "subjects": [{"kind": "ServiceAccount", "name": sa, "namespace": ns}]})
    for p in spec.get("permissions", []):
        sa = p["serviceAccountName"]
        out.append({"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "Role", "metadata": {"name": sa, "namespace": ns}, "rules": p["rules"]})
        out.append({"apiVersion": "rbac.authorization.k8s.io/v1", "kind": "RoleBinding", "metadata": {"name": sa, "namespace": ns},
                    "roleRef": {"apiGroup": "rbac.authorization.k8s.io", "kind": "Role", "name": sa},
                    "subjects": [{"kind": "ServiceAccount", "name": sa, "namespace": ns}]})
    for dep in spec["deployments"]:
        out.append({"apiVersion": "apps/v1", "kind": "Deployment",
                    "metadata": {"name": dep["name"], "namespace": ns, "labels": dep.get("label", {})}, "spec": dep["spec"]})
    sys.stdout.write(f"# Generated by kube/ha/fencing/from-bundle.py from {path.rsplit('/', 1)[-1]} (namespace {ns}): do not edit.\n")
    yaml.safe_dump_all(out, sys.stdout, sort_keys=True, explicit_start=True)


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    main(sys.argv[1], sys.argv[2])
