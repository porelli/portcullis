#!/usr/bin/env python3
"""Generate charts/portcullis/images.yaml from docker-compose.yml (K1).

Every compose service that exists on Kubernetes gets one entry:
  - a third-party image: its compose ref, fully qualified, tag@sha256;
  - a core-built image (group-gate, enroll, domains -- dns-tool shares it --,
    mcp-gate, wg) and the Hub / Keycloak defaults: {tag_ref: <ref>:edge},
    which the CLI resolves to a digest at up / upgrade, so the chart only
    ever sees name@sha256:... .
The socket proxies have no Kubernetes form (the Roles replace them).

  scripts/gen-images-yaml.py           rewrite the file
  scripts/gen-images-yaml.py --check   exit 1 when the file is stale
"""
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
COMPOSE = ROOT / "docker-compose.yml"
OUT = ROOT / "charts" / "portcullis" / "images.yaml"

REGISTRY = "ghcr.io/porelli/portcullis-"
CORE_BUILT = ("group-gate", "enroll", "domains", "mcp-gate", "wg")
ABSENT = ("socket-proxy-traefik", "socket-proxy-hub")
PINNED = re.compile(r"^[a-z0-9.-]+\.[a-z]+(:[0-9]+)?/[a-z0-9._/-]+:[A-Za-z0-9._-]+@sha256:[0-9a-f]{64}$")
DEFAULT = re.compile(r"^\$\{[A-Z_]+:-(ghcr\.io/porelli/portcullis-[a-z-]+:edge)\}$")

HEADER = """\
# Generated by scripts/gen-images-yaml.py from docker-compose.yml: do not
# edit (CI unit-tests fails when it is stale). A string is a third-party
# image pinned tag@sha256; {tag_ref: ...} is a core-built image, the Hub or
# Keycloak, resolved to a digest by ./portcullis up / upgrade (K1).
"""


def entries(compose):
    out = {}
    for name, svc in sorted(compose["services"].items()):
        if name in ABSENT:
            continue
        image = svc.get("image") or ""
        built = "build" in svc or image.startswith("portcullis-")
        if built:
            base = image[len("portcullis-"):] if image else name
            if base not in CORE_BUILT:
                raise SystemExit(f"{name}: a locally built image ({image or name}) that isn't one of {', '.join(CORE_BUILT)}")
            out[name] = {"tag_ref": f"{REGISTRY}{base}:edge"}
            continue
        m = DEFAULT.match(image)
        if m:
            out[name] = {"tag_ref": m.group(1)}
            continue
        if not PINNED.match(image):
            raise SystemExit(f"{name}: image {image!r} is not fully qualified and pinned tag@sha256")
        out[name] = image
    return out


def render():
    compose = yaml.safe_load(COMPOSE.read_text())
    body = yaml.safe_dump({"images": entries(compose)}, sort_keys=True, default_flow_style=False, width=200)
    return HEADER + body


def main(argv):
    text = render()
    if argv[1:] == ["--check"]:
        have = OUT.read_text() if OUT.exists() else ""
        if have != text:
            print(f"{OUT.relative_to(ROOT)} is stale: run scripts/gen-images-yaml.py", file=sys.stderr)
            return 1
        return 0
    if argv[1:]:
        print("usage: gen-images-yaml.py [--check]", file=sys.stderr)
        return 2
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
