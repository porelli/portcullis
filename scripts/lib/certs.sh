# shellcheck shell=bash
#
# `portcullis cert enroll|renew|revoke|list|sync` — client certificates.
#
# How revocation is enforced: Traefik does NOT check CRLs. group-gate
# (portcullis-groups@docker) denies any request whose TLS client cert has a
# revoked serial. It learns revoked serials from
#   - certs/revocation/revoked-serials.txt (rewritten from Vault's
#     authoritative list by `cert revoke` / `cert sync`; next request), and
#   - Vault's CRL (http://vault:8200/v1/pki_int/crl, re-fetched every 60s),
#     which also covers revocations done via the Vault API/UI directly.
# Only routers whose middleware chain has client-headers@file BEFORE
# portcullis-groups@docker are covered.

REVOKED_FILE="${REVOKED_FILE:-$PORTCULLIS_ROOT/certs/revocation/revoked-serials.txt}"

# cert_warn_seconds — "expiring" threshold for cert list / status
# (CERT_EXPIRY_WARN_DAYS, default 7).
cert_warn_seconds() {
  local d="${CERT_EXPIRY_WARN_DAYS:-7}"
  [[ "$d" =~ ^[0-9]+$ ]] || d=7
  echo $((d * 86400))
}

# write_revoked_serials <file> — atomically rewrite the revoked-serial list
# read by group-gate from Vault's authoritative list (pki_int/certs/revoked).
# Needs an admin VAULT_TOKEN and a `vault` command. Fails — leaving <file>
# untouched — on ANY error other than Vault's "nothing to list" (exit 2):
# an empty list caused by a sealed Vault / bad token / network error must
# never un-revoke certs.
write_revoked_serials() {
  local file="$1" dir out rc=0 serials tmp
  dir="$(dirname "$file")"
  out="$(vault list -format=json pki_int/certs/revoked 2>&1)" || rc=$?
  case "$rc" in
    0)
      serials="$(printf '%s' "$out" | jq -r 'if type == "array" then .[] else error("not an array") end' 2>/dev/null)" || {
        echo "ERROR: unexpected output from 'vault list pki_int/certs/revoked' — $file left unchanged" >&2
        return 1
      }
      ;;
    2)
      # vault CLI: exit 2 = no values at that path (no revoked certs).
      serials=""
      ;;
    *)
      echo "ERROR: 'vault list pki_int/certs/revoked' failed (exit $rc) — $file left unchanged:" >&2
      printf '%s\n' "$out" | sed 's/^/    /' >&2
      return 1
      ;;
  esac
  mkdir -p "$dir" || return 1
  [ -w "$dir" ] || { echo "ERROR: $dir is not writable (fix: sudo chown \"$(id -un)\" \"$dir\")" >&2; return 1; }
  tmp="$(mktemp "$dir/.revoked.XXXXXX")" || return 1
  {
    echo "# Revoked client-cert serials (Vault pki_int), generated by portcullis"
    echo "# on $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not edit; run: ./portcullis cert sync"
    if [ -n "$serials" ]; then printf '%s\n' "$serials"; fi
  } > "$tmp" && chmod 644 "$tmp" && mv -f "$tmp" "$file" || { rm -f "$tmp"; return 1; }
}

cert_sync() {
  write_revoked_serials "$REVOKED_FILE" || fail "Could not refresh $REVOKED_FILE (left unchanged)."
  ok "Revoked-serial list updated: $REVOKED_FILE ($(grep -vc '^#' "$REVOKED_FILE" || true) serial(s))"
}

# _cert_info <serial> — prints "<cn>|<not-after>|<revoked:true|false>".
_cert_info() {
  local data pem cn end rt
  data="$(vault read -format=json "pki_int/cert/$1" 2>/dev/null)" || return 1
  pem="$(printf '%s' "$data" | jq -r '.data.certificate')"
  rt="$(printf '%s' "$data" | jq -r '.data.revocation_time // 0')"
  cn="$(printf '%s\n' "$pem" | openssl x509 -noout -subject 2>/dev/null | sed 's/.*CN *= *//; s/,.*//')"
  end="$(printf '%s\n' "$pem" | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2)"
  if [ "$rt" != 0 ] && [ "$rt" != null ]; then rt=true; else rt=false; fi
  printf '%s|%s|%s\n' "$cn" "$end" "$rt"
}

cert_list() {
  local show_revoked="$1" serials serial info cn end revoked now epoch status warn_s
  serials="$(vault list -format=json pki_int/certs 2>/dev/null)" || fail "Cannot list certs. Is Vault running and unsealed?"
  now="$(date +%s)"
  warn_s="$(cert_warn_seconds)"
  printf '%-40s %-24s %-9s %s\n' SERIAL "COMMON NAME" STATUS EXPIRES
  for serial in $(printf '%s' "$serials" | jq -r '.[]'); do
    info="$(_cert_info "$serial")" || continue
    IFS='|' read -r cn end revoked <<< "$info"
    epoch="$(to_epoch "$end")"
    if [ "$revoked" = true ]; then
      [ "$show_revoked" = true ] || continue
      status="${C_RED}revoked${C_NC}"
    elif [ "$epoch" -lt "$now" ]; then
      status="${C_RED}expired${C_NC}"
    elif [ $((epoch - now)) -lt "$warn_s" ]; then
      status="${C_YELLOW}expiring${C_NC}"
    else
      status="${C_GREEN}valid${C_NC}"
    fi
    printf '%-40s %-24s %-9s %s\n' "$serial" "$cn" "$status" "$end"
  done
}

cert_revoke() {
  local serial="$1" assume_yes="$2" info cn end revoked crl
  info "Looking up certificate $serial..."
  info="$(_cert_info "$serial")" || fail "Certificate not found: $serial"
  IFS='|' read -r cn end revoked <<< "$info"
  if [ "$revoked" = true ]; then
    warn "Certificate is already revoked."
    cert_sync
    return 0
  fi
  printf '\n  Subject:  %s\n  Serial:   %s\n  Expires:  %s\n\n' "$cn" "$serial" "$end"
  if [ "$assume_yes" != true ]; then
    confirm "Revoke this certificate?" || { echo "Cancelled."; return 0; }
  fi
  vault write pki_int/revoke serial_number="$serial" >/dev/null || fail "Revocation failed"
  ok "Certificate revoked in Vault."
  # Vault rebuilds the CRL on revoke; this is belt and braces.
  vault read -format=json pki_int/crl/rotate >/dev/null 2>&1 || warn "CRL rotate failed (group-gate still uses the serial file)"
  # Enforce: group-gate reads this file on every request.
  cert_sync
  # PEM copy of the CRL for tools that want one (e.g. Keycloak X.509 CRL
  # checking with a file URL). NOT used by Traefik.
  crl="$(curl -sf "$VAULT_ADDR/v1/pki_int/crl/pem" 2>/dev/null || true)"
  [ -z "$crl" ] || printf '%s\n' "$crl" > "$PORTCULLIS_ROOT/certs/crl.pem"
  ok "Requests with this certificate are now denied by group-gate on every router"
  ok "using client-headers@file + portcullis-groups@docker (all core routers and"
  ok "the default app templates). Sessions that reached an mtls-only policy with it"
  ok "need the (now revoked) cert on every request, so they stop working too, and"
  ok "Keycloak refuses new X.509 logins with it (CRL, refreshed within 60s)."
  warn "NOT covered: routers relying on the TLS client cert alone (protected tier"
  warn "without portcullis-groups@docker) — Traefik does not check CRLs; the cert"
  warn "keeps working there until it expires. Password/WebAuthn sessions of the"
  warn "user are not affected: sign them out in the Keycloak admin console if needed."
}

# _cert_issue <user> <email> <slot> <ttl> <tmpdir> — CSR from the key in
# <slot> (public key in <tmpdir>/pubkey.pem), signed by Vault, written back.
_cert_issue() {
  local user="$1" email="$2" slot="$3" ttl="$4" tmp="$5"
  # ykman prompts for the PIN unless PIV_PIN is set (then it is passed on
  # the ykman command line, visible in `ps`).
  local -a pin=()
  [ -z "${PIV_PIN:-}" ] || pin=(--pin "$PIV_PIN")
  info "Generating CSR on the YubiKey..."
  ykman piv certificates request --subject "CN=${user},emailAddress=${email}" \
    --hash-algorithm SHA256 ${pin[@]+"${pin[@]}"} "$slot" "$tmp/pubkey.pem" "$tmp/request.csr"
  info "Requesting a signed certificate from Vault..."
  # common_name is mandatory: the client-cert role ignores the CSR subject.
  vault write -format=json pki_int/sign/client-cert \
    csr="$(cat "$tmp/request.csr")" common_name="$user" ttl="$ttl" \
    | jq -r '.data.certificate' > "$tmp/client.crt"
  info "Writing the certificate to PIV slot $slot..."
  ykman piv certificates import --verify ${pin[@]+"${pin[@]}"} "$slot" "$tmp/client.crt"
}

# cert_enroll <renew:true|false> <user> <email> <slot> <ttl>
cert_enroll() {
  local renew="$1" user="$2" email="$3" slot="$4" ttl="$5" tmp
  require_cmd ykman jq openssl
  vault_admin
  tmp="$(mktemp -d)"
  # shellcheck disable=SC2064  # expand $tmp now
  trap "rm -rf '$tmp'" EXIT
  ykman info >/dev/null 2>&1 || fail "No YubiKey detected. Insert your YubiKey and try again."
  local -a pin=()
  [ -z "${PIV_PIN:-}" ] || pin=(--pin "$PIV_PIN")
  if [ "$renew" = true ]; then
    info "Exporting the public key from slot $slot..."
    ykman piv keys export "$slot" "$tmp/pubkey.pem" 2>/dev/null \
      || fail "No key in slot $slot. Run ./portcullis cert enroll first."
  else
    info "Generating a key pair on the YubiKey (slot $slot, ECCP256, touch: cached)..."
    if ! ykman piv keys generate --algorithm ECCP256 --pin-policy DEFAULT --touch-policy CACHED \
        ${pin[@]+"${pin[@]}"} "$slot" "$tmp/pubkey.pem" 2>/dev/null; then
      warn "Slot $slot already has a key — overwriting it."
      ykman piv keys generate --algorithm ECCP256 --pin-policy DEFAULT --touch-policy CACHED \
        --force ${pin[@]+"${pin[@]}"} "$slot" "$tmp/pubkey.pem"
    fi
  fi
  _cert_issue "$user" "$email" "$slot" "$ttl" "$tmp"
  ok "Certificate for $user written to slot $slot (TTL $ttl)."
  echo "    Verify:  ykman piv certificates export $slot - | openssl x509 -text -noout"
  echo "    Renew:   before it expires, at https://enroll.${PORTCULLIS_DOMAIN:-<domain>}/self"
  echo "             (the user, with the key inserted) or ./portcullis cert renew $user $email"
}

help_cert() {
  cat <<'EOF'
Usage: portcullis cert <subcommand>

  enroll    Generate a key on a YubiKey (PIV) and write a Vault-signed cert to it
  renew     Re-issue the cert for the key already on the YubiKey
  revoke    Revoke a cert by serial (enforced by group-gate)
  list      List issued certificates
  sync      Rewrite certs/revocation/revoked-serials.txt from Vault

Run 'portcullis cert <subcommand> --help' for details.
EOF
}

_help_cert_enroll_common() {
  cat <<'EOF'
Options:
  --slot SLOT   PIV slot (default: $PIV_SLOT or 9a, Authentication)
  --ttl TTL     certificate lifetime (default: $CLIENT_CERT_TTL or 720h; the
                Vault role caps it at CLIENT_CERT_TTL as of the last pki setup)

Environment:
  PIV_PIN       YubiKey PIV PIN. If unset, ykman prompts for it (preferred:
                a PIN given here appears on the ykman command line).
  VAULT_TOKEN   admin token (default: root token from secrets/vault-init.json)
  VAULT_ADDR    default http://127.0.0.1:8200

Needs ykman, openssl, jq and Vault access (run on the Portcullis host, or
export VAULT_ADDR/VAULT_TOKEN). The cert CN is <username>.
EOF
}

help_cert_enroll() {
  echo "Usage: portcullis cert enroll [--slot SLOT] [--ttl TTL] <username> [email]"
  echo ""
  echo "Generate a new ECCP256 key pair on the YubiKey (overwrites the slot), create a"
  echo "CSR, have Vault sign it and import the certificate into the slot."
  echo ""
  _help_cert_enroll_common
}

