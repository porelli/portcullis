help_cert_sync() {
  cat <<'EOF'
Usage: portcullis cert sync

Rewrite certs/revocation/revoked-serials.txt from Vault's list of revoked
serials (atomic). If Vault cannot be queried (sealed, bad token,
unreachable) the file is left unchanged and the command fails — it never
"un-revokes" by writing an empty list.
EOF
}

cmd_cert() {
  local sub="${1:-}"
  [ $# -gt 0 ] && shift
  case "$sub" in
    ""|-h|--help|help) help_cert; [ -n "$sub" ] || exit 2; return 0 ;;
    enroll|renew|revoke|list|sync) ;;
    *) usage_error cert "unknown subcommand: $sub" ;;
  esac
  local slot="${PIV_SLOT:-9a}" ttl="${TTL:-${CLIENT_CERT_TTL:-720h}}" yes=false all=false
  local -a pos=()
  while [ $# -gt 0 ]; do
    case "$sub:$1" in
      *:-h|*:--help) "help_cert_$sub"; return 0 ;;
      enroll:--slot|renew:--slot) need_value "cert $sub" "$1" "${2:-}"; slot="$2"; shift ;;
      enroll:--ttl|renew:--ttl) need_value "cert $sub" "$1" "${2:-}"; ttl="$2"; shift ;;
      revoke:-y|revoke:--yes) yes=true ;;
      list:--all) all=true ;;
      *:-*) usage_error "cert $sub" "unknown option: $1" ;;
      *) pos+=("$1") ;;
    esac
    shift
  done
  local npos=${#pos[@]}
  case "$sub" in
    enroll|renew)
      [ "$npos" -ge 1 ] && [ "$npos" -le 2 ] || usage_error "cert $sub" "expected <username> [email]"
      [[ "${pos[0]}" =~ ^[A-Za-z0-9._@-]+$ ]] || usage_error "cert $sub" "invalid username: ${pos[0]}"
      ;;
    revoke) [ "$npos" -eq 1 ] || usage_error "cert revoke" "expected exactly one <serial>" ;;
    *) [ "$npos" -eq 0 ] || usage_error "cert $sub" "unexpected argument: ${pos[0]}" ;;
  esac
  need_env
  case "$sub" in
    enroll|renew)
      local email="${pos[0]}@${PORTCULLIS_DOMAIN:-portcullis.local}"
      [ "$npos" -lt 2 ] || email="${pos[1]}"
      local renew=false
      [ "$sub" = enroll ] || renew=true
      cert_enroll "$renew" "${pos[0]}" "$email" "$slot" "$ttl"
      ;;
    revoke) require_cmd jq openssl; vault_admin; cert_revoke "${pos[0]}" "$yes" ;;
    list)   require_cmd jq openssl; vault_admin; cert_list "$all" ;;
    sync)   require_cmd jq; vault_admin; cert_sync ;;
  esac
}
