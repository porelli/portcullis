# shellcheck shell=bash
#
# `portcullis cert enroll|renew|revoke|list|sync` — YubiKey and browser
# certificates, issued by the internal certificate authority: pki_int
# (YubiKey certificates) and pki_file (browser certificates, created by
# people on the Sign-in page). revoke, list and sync cover both.
#
# How revocation is enforced: Traefik does NOT check CRLs. group-gate
# (portcullis-groups@docker) denies any request whose TLS client cert has a
# revoked serial. It learns revoked serials from
#   - certs/revocation/revoked-serials.txt (rewritten from Vault's
#     authoritative lists of both CAs by `cert revoke` / `cert sync`; next
#     request), and
#   - Vault's full + delta CRLs of both CAs (http://vault:8200/v1/<mount>/crl
#     and .../crl/delta, re-fetched every 60s), which also cover revocations
#     done via the Vault API/UI directly. Both CAs have auto_rebuild=true, so
#     Vault does not rebuild the full CRL on revoke: a direct revocation
#     shows up in the delta CRL (rebuilt about once a minute) and in the
#     full CRL at its next rebuild. `cert revoke` rotates the full CRL of
#     the certificate's CA right away. Keycloak's certificate sign-in checks
#     both CRLs of its CA too.
# Only routers whose middleware chain has client-headers@file BEFORE
# portcullis-groups@docker are covered.

# The two issuing CAs and the kind each one issues (cert list's KIND).
CERT_MOUNTS="pki_int pki_file"
cert_kind() { case "$1" in pki_int) echo YubiKey ;; pki_file) echo Browser ;; *) echo "?" ;; esac; }

REVOKED_FILE="${REVOKED_FILE:-$PORTCULLIS_ROOT/certs/revocation/revoked-serials.txt}"

# cert_warn_seconds — "expiring" threshold for cert list / status
# (CERT_EXPIRY_WARN_DAYS, default 7).
cert_warn_seconds() {
  local d="${CERT_EXPIRY_WARN_DAYS:-7}"
  [[ "$d" =~ ^[0-9]+$ ]] || d=7
  echo $((d * 86400))
}

# write_revoked_serials <file> — atomically rewrite the revoked-serial list
# read by group-gate from Vault's authoritative lists: the union of
# pki_int/certs/revoked and pki_file/certs/revoked. Needs an admin
# VAULT_TOKEN and a `vault` command. Fails — leaving <file> untouched — on
# ANY answer of either list other than a JSON array or Vault's "No value
# found" (vault_no_value; the CLI's exit 2 alone is also every API error):
# an empty list caused by a sealed Vault / bad token / network error must
# never un-revoke certs.
write_revoked_serials() {
  local file="$1" dir out rc mount serials="" got tmp
  dir="$(dirname "$file")"
  for mount in $CERT_MOUNTS; do
    rc=0
    out="$(vault list -format=json "$mount/certs/revoked" 2>&1)" || rc=$?
    case "$rc" in
      0)
        got="$(printf '%s' "$out" | jq -r 'if type == "array" then .[] else error("not an array") end' 2>/dev/null)" || {
          echo "ERROR: unexpected output from 'vault list $mount/certs/revoked' — $file left unchanged" >&2
          return 1
        }
        [ -z "$got" ] || serials+="$got"$'\n'
        ;;
      2)
        # "No value found" = nothing revoked on that CA; any other exit-2
        # answer is an API error (403, sealed, unreachable).
        vault_no_value "$out" && continue
        echo "ERROR: 'vault list $mount/certs/revoked' failed (exit $rc) — $file left unchanged:" >&2
        printf '%s\n' "$out" | sed 's/^/    /' >&2
        return 1
        ;;
      *)
        echo "ERROR: 'vault list $mount/certs/revoked' failed (exit $rc) — $file left unchanged:" >&2
        printf '%s\n' "$out" | sed 's/^/    /' >&2
        return 1
        ;;
    esac
  done
  mkdir -p "$dir" || return 1
  if [ ! -w "$dir" ]; then
    if _rt_is_podman; then
      echo "ERROR: $dir is not writable (fix: podman unshare chown 0:0 \"$dir\")" >&2
    else
      echo "ERROR: $dir is not writable (fix: sudo chown \"$(id -un)\" \"$dir\")" >&2
    fi
    return 1
  fi
  tmp="$(mktemp "$dir/.revoked.XXXXXX")" || return 1
  {
    echo "# Revoked YubiKey and browser certificate serials (Vault pki_int + pki_file),"
    echo "# generated by portcullis on $(date -u +%Y-%m-%dT%H:%M:%SZ) — do not edit; run: ./portcullis cert sync"
    if [ -n "$serials" ]; then printf '%s' "$serials" | sort -u; fi
  } > "$tmp" && chmod 644 "$tmp" && mv -f "$tmp" "$file" || { rm -f "$tmp"; return 1; }
}

cert_sync() {
  write_revoked_serials "$REVOKED_FILE" || fail "Could not refresh $REVOKED_FILE (left unchanged)."
  # Kubernetes: the certs-revocation ConfigMap now, and group-gate's pod
  # annotation bumped so the kubelet resyncs the volume at once.
  if _rt_is_kube; then kube_revocation_bump || fail "could not deliver the revoked-serial list to group-gate (ConfigMap certs-revocation)"; fi
  ok "Revoked-serial list updated: $REVOKED_FILE ($(grep -vc '^#' "$REVOKED_FILE" || true) serial(s))"
}

# _cert_read <mount> <serial> — prints Vault's JSON for the certificate.
# Returns 0 found, 2 not on that mount, 1 any other error (sealed, token...).
_cert_read() {
  local rc=0 out
  out="$(vault read -format=json "$1/cert/$2" 2>&1)" || rc=$?
  if [ "$rc" = 0 ] && printf '%s' "$out" | jq -e '.data.certificate | type == "string" and length > 0' >/dev/null 2>&1; then
    printf '%s\n' "$out"
    return 0
  fi
  # Only Vault's own "No value found" (exit 2) means "not on this mount";
  # every other answer (403, sealed, unreachable, exit 0 without a
  # certificate) is an error.
  if [ "$rc" = 2 ] && vault_no_value "$out"; then return 2; fi
  printf '%s\n' "$out" >&2
  return 1
}

# _cert_parse — Vault's certificate JSON on stdin → "<cn>|<not-after>|<revoked:true|false>".
_cert_parse() {
  local data pem cn end rt
  data="$(cat)"
  pem="$(printf '%s' "$data" | jq -r '.data.certificate')" || return 1
  rt="$(printf '%s' "$data" | jq -r '.data.revocation_time // 0')" || return 1
  cn="$(printf '%s\n' "$pem" | openssl x509 -noout -subject 2>/dev/null | sed 's/.*CN *= *//; s/,.*//')"
  end="$(printf '%s\n' "$pem" | openssl x509 -noout -enddate 2>/dev/null | cut -d= -f2)"
  if [ "$rt" != 0 ] && [ "$rt" != null ]; then rt=true; else rt=false; fi
  printf '%s|%s|%s\n' "$cn" "$end" "$rt"
}

# _cert_info <mount> <serial> — prints "<cn>|<not-after>|<revoked:true|false>".
_cert_info() {
  local data
  data="$(_cert_read "$1" "$2" 2>/dev/null)" || return 1
  printf '%s' "$data" | _cert_parse
}

# _cert_serials <mount> — the mount's issued serials, one per line. Vault's
# "No value found" (nothing issued yet) is an empty list; anything but a
# JSON array fails (a sealed Vault can answer exit 0 with no list at all).
_cert_serials() {
  local rc=0 out
  out="$(vault list -format=json "$1/certs" 2>&1)" || rc=$?
  case "$rc" in
    0) printf '%s' "$out" | jq -er 'if type == "array" then .[] else error("not an array") end' 2>/dev/null \
         || { [ "$(printf '%s' "$out" | jq -c . 2>/dev/null)" = "[]" ]; } ;;
    2) vault_no_value "$out" ;;
    *) return 1 ;;
  esac
}

cert_list() {
  local show_revoked="$1" mount kind serials serial info cn end revoked now epoch status warn_s
  now="$(date +%s)"
  warn_s="$(cert_warn_seconds)"
  printf '%-40s %-8s %-24s %-9s %s\n' SERIAL KIND "COMMON NAME" STATUS EXPIRES
  for mount in $CERT_MOUNTS; do
    kind="$(cert_kind "$mount")"
    serials="$(_cert_serials "$mount")" || fail "Cannot list $mount certificates. Is Vault running and unsealed?"
    for serial in $serials; do
      info="$(_cert_info "$mount" "$serial")" || continue
      IFS='|' read -r cn end revoked <<< "$info"
      epoch="$(to_epoch "$end")"
      if [ "$revoked" = true ]; then
        [ "$show_revoked" = true ] || continue
        status="${C_RED}revoked${C_NC}"
      elif [ "$epoch" -lt "$now" ]; then
        status="${C_RED}expired${C_NC}"
      elif [ $((epoch - now)) -lt "$warn_s" ]; then
        status="${C_YELLOW}expiring${C_NC}"
      else
        status="${C_GREEN}valid${C_NC}"
      fi
      printf '%-40s %-8s %-24s %-9s %s\n' "$serial" "$kind" "$cn" "$status" "$end"
    done
  done
}

cert_revoke() {
  local serial="$1" assume_yes="$2" mount="" m data rc info cn end revoked kind
  info "Looking up certificate $serial..."
  # enroll's order: pki_int, then pki_file. Only "not on this mount" moves on;
  # any other Vault error stops here.
  for m in $CERT_MOUNTS; do
    rc=0
    data="$(_cert_read "$m" "$serial")" || rc=$?
    case "$rc" in
      0) mount="$m"; break ;;
      2) ;;
      *) fail "Cannot read certificate $serial from $m. Is Vault running and unsealed?" ;;
    esac
  done
  [ -n "$mount" ] || fail "Certificate not found: $serial"
  info="$(printf '%s' "$data" | _cert_parse)" || fail "Cannot read certificate $serial"
  IFS='|' read -r cn end revoked <<< "$info"
  kind="$(cert_kind "$mount")"
  if [ "$revoked" = true ]; then
    warn "Certificate is already revoked."
    cert_sync
    return 0
  fi
  printf '\n  Kind:     %s certificate (%s)\n  Subject:  %s\n  Serial:   %s\n  Expires:  %s\n\n' "$kind" "$mount" "$cn" "$serial" "$end"
  if [ "$assume_yes" != true ]; then
    confirm "Revoke this certificate?" || { echo "Cancelled."; return 0; }
  fi
  vault write "$mount/revoke" serial_number="$serial" >/dev/null || fail "Revocation failed"
  ok "Certificate revoked in Vault ($mount)."
  # auto_rebuild=true: Vault does NOT rebuild the full CRL on revoke (the
  # serial would otherwise only reach the delta CRL within ~1-2 minutes).
  # Rebuild it now so Keycloak and group-gate see it on their next fetch.
  vault read -format=json "$mount/crl/rotate" >/dev/null 2>&1 \
    || warn "CRL rotate failed: the delta CRL picks the revocation up within ~2 minutes (group-gate uses the serial file now)"
  # Enforce: group-gate reads this file on every request.
  cert_sync
  ok "Requests with this certificate are now denied by group-gate on every router"
  ok "using client-headers@file + portcullis-groups@docker (all core routers and"
  ok "the default app templates). Sessions that needed the certificate need it on"
  ok "every request, so they stop working too, and Keycloak refuses new sign-ins"
  ok "with it (CRL, refreshed within 60s)."
  warn "NOT covered: routers relying on the certificate at the TLS handshake alone (protected /"
  warn "protected-any options without portcullis-groups@docker) — Traefik does not"
  warn "check CRLs; the certificate keeps working there until it expires. The person's"
  warn "passkey and password sessions are not affected: sign them out in the Keycloak"
  warn "admin console if needed."
}

# _cert_issue <user> <email> <slot> <ttl> <tmpdir> — CSR from the key in
# <slot> (public key in <tmpdir>/pubkey.pem), signed by Vault, written back.
_cert_issue() {
  local user="$1" email="$2" slot="$3" ttl="$4" tmp="$5"
  # ykman prompts for the PIN unless PIV_PIN is set (then it is passed on
  # the ykman command line, visible in `ps`).
  local -a pin=()
  [ -z "${PIV_PIN:-}" ] || pin=(--pin "$PIV_PIN")
  info "Generating CSR on the YubiKey..."
  ykman piv certificates request --subject "CN=${user},emailAddress=${email}" \
    --hash-algorithm SHA256 ${pin[@]+"${pin[@]}"} "$slot" "$tmp/pubkey.pem" "$tmp/request.csr"
  info "Requesting a signed certificate from Vault..."
  # common_name is mandatory: the client-cert role ignores the CSR subject.
  vault write -format=json pki_int/sign/client-cert \
    csr="$(cat "$tmp/request.csr")" common_name="$user" ttl="$ttl" \
    | jq -r '.data.certificate' > "$tmp/client.crt"
  info "Writing the certificate to PIV slot $slot..."
  ykman piv certificates import --verify ${pin[@]+"${pin[@]}"} "$slot" "$tmp/client.crt"
}

# cert_enroll <renew:true|false> <user> <email> <slot> <ttl>
cert_enroll() {
  local renew="$1" user="$2" email="$3" slot="$4" ttl="$5" tmp
  require_cmd ykman jq openssl
  vault_admin
  tmp="$(mktemp -d)"
  # shellcheck disable=SC2064  # expand $tmp now
  trap "rm -rf '$tmp'" EXIT
  ykman info >/dev/null 2>&1 || fail "No YubiKey detected. Insert your YubiKey and try again."
  local -a pin=()
  [ -z "${PIV_PIN:-}" ] || pin=(--pin "$PIV_PIN")
  if [ "$renew" = true ]; then
    info "Exporting the public key from slot $slot..."
    ykman piv keys export "$slot" "$tmp/pubkey.pem" 2>/dev/null \
      || fail "No key in slot $slot. Run ./portcullis cert enroll first."
  else
    info "Generating a key pair on the YubiKey (slot $slot, ECCP256, touch: cached)..."
    if ! ykman piv keys generate --algorithm ECCP256 --pin-policy DEFAULT --touch-policy CACHED \
        ${pin[@]+"${pin[@]}"} "$slot" "$tmp/pubkey.pem" 2>/dev/null; then
      warn "Slot $slot already has a key — overwriting it."
      ykman piv keys generate --algorithm ECCP256 --pin-policy DEFAULT --touch-policy CACHED \
        --force ${pin[@]+"${pin[@]}"} "$slot" "$tmp/pubkey.pem"
    fi
  fi
  _cert_issue "$user" "$email" "$slot" "$ttl" "$tmp"
  ok "YubiKey certificate for $user written to slot $slot (TTL $ttl)."
  echo "    Verify:  ykman piv certificates export $slot - | openssl x509 -text -noout"
  echo "    Renew:   before it expires, on the Sign-in page, https://people.${PORTCULLIS_DOMAIN:-<domain>}/signin"
  echo "             (the person, with the YubiKey inserted) or ./portcullis cert renew $user $email"
}

help_cert() {
  cat <<'EOF'
Usage: portcullis cert <subcommand>

YubiKey and browser certificates (the internal certificate authority:
pki_int issues YubiKey certificates, pki_file browser certificates).

  enroll    Generate a key on a YubiKey (PIV) and write a YubiKey certificate to it
  renew     Issue a new YubiKey certificate for the key already on the YubiKey
  revoke    Revoke a YubiKey or browser certificate by serial (enforced by group-gate)
  list      List issued YubiKey and browser certificates
  sync      Rewrite certs/revocation/revoked-serials.txt from Vault (both CAs)

People create browser certificates on the Sign-in page
(https://people.<domain>/signin); there is no CLI command for them.

Run 'portcullis cert <subcommand> --help' for details.
EOF
}

