# shellcheck shell=bash
#
# The session store (compose service `sessions`, Valkey): both oauth2-proxies
# keep their sessions there and the browser holds only a small ticket cookie
# (`_oauth2_proxy` / `__Host-portcullis_ext`, oauth2-proxy's redis session
# store). oauth2-proxy v7.15.5's cookie store never expires the unsplit
# cookie once a session grows past one cookie (_oauth2_proxy_0..n) and keeps
# loading the stale one first (upstream issue #3486, fix #3491 unreleased):
# the first step-up after a setup link looped on group-gate's step-up page.
#
#   secrets/sessions/valkey.conf  generated here from .env on every
#                                 init / up / upgrade / restore (never
#                                 edited by hand); 0640, group 1000 (the
#                                 image's valkey group, compose user
#                                 999:1000); mounted read-only at
#                                 /etc/valkey/valkey.conf. It holds the
#                                 SHA-256 of FORWARD_AUTH_REDIS_PASSWORD /
#                                 FORWARD_AUTH_EXT_REDIS_PASSWORD, never the
#                                 passwords themselves.
#
# The directory is 0700: nothing traverses it (single-file bind mount).
#
# ACL: the default user is off (no password, no commands, no keys); each
# oauth2-proxy has its own user limited to its own keys — ticket ids are
# `<cookie name>-<32 hex>` (oauth2-proxy pkg/sessions/persistence/ticket.go)
# and their refresh locks `<ticket id>.lock` (pkg/sessions/redis/lock.go) —
# and to the commands oauth2-proxy v7.15.5 sends (go-redis v9.22.0,
# bsm/redislock v0.10.0):
#   ping                          startup VerifyConnection
#   get set del                   session Load / Save (SET … PX) / Clear
#   evalsha eval                  redislock's Lua scripts (EVALSHA, EVAL on
#                                 NOSCRIPT); the scripts' own calls are
#                                 checked against the same user:
#   msetnx mset getrange pexpire  obtain.lua (lock taken / overridden + TTL)
#   mget                          release.lua / refresh.lua (value check;
#                                 then del / pexpire)
# HELLO / AUTH need no grant; go-redis's CLIENT SETINFO and CLIENT
# MAINT_NOTIFICATIONS are refused (NOPERM) and it carries on without them.

SESSIONS_CONF_CHANGED=false
SESSIONS_FWD_USER="forward-auth"
SESSIONS_FWD_EXT_USER="forward-auth-ext"
# Ticket key patterns = the cookie names (docker-compose.yml: forward-auth's
# default _oauth2_proxy, forward-auth-ext's OAUTH2_PROXY_COOKIE_NAME).
SESSIONS_FWD_KEYS="_oauth2_proxy-*"
SESSIONS_FWD_EXT_KEYS="__Host-portcullis_ext-*"
SESSIONS_ACL_COMMANDS="+ping +get +set +del +evalsha +eval +msetnx +mset +getrange +pexpire +mget"

_sessions_dir() { echo "$PORTCULLIS_ROOT/secrets/sessions"; }

# _sessions_hash — SHA-256 (hex) of stdin; the password never reaches argv.
_sessions_hash() { openssl dgst -sha256 -r | cut -d' ' -f1; }

# sessions_conf — the whole valkey.conf on stdout (needs both passwords in
# the environment: env_load).
sessions_conf() {
  local fwd ext
  fwd="$(printf '%s' "$FORWARD_AUTH_REDIS_PASSWORD" | _sessions_hash)"
  ext="$(printf '%s' "$FORWARD_AUTH_EXT_REDIS_PASSWORD" | _sessions_hash)"
  [[ "$fwd" =~ ^[0-9a-f]{64}$ ]] && [[ "$ext" =~ ^[0-9a-f]{64}$ ]] || fail "could not hash the session store passwords (openssl)"
  cat <<EOF
# Generated by ./portcullis from .env (scripts/lib/sessions.sh). Do not edit:
# every init / up / upgrade / restore rewrites it.
port 6379
protected-mode yes
# No persistence: sessions live in memory only (a restart signs everyone out).
save ""
appendonly no
dir /data
maxmemory 64mb
maxmemory-policy volatile-ttl
enable-debug-command no
enable-module-command no
enable-protected-configs no
loglevel notice
logfile ""
user default off resetpass resetkeys resetchannels -@all
user $SESSIONS_FWD_USER on resetpass resetkeys resetchannels -@all $SESSIONS_ACL_COMMANDS ~$SESSIONS_FWD_KEYS #$fwd
user $SESSIONS_FWD_EXT_USER on resetpass resetkeys resetchannels -@all $SESSIONS_ACL_COMMANDS ~$SESSIONS_FWD_EXT_KEYS #$ext
EOF
}

# sessions_prepare — (re)write secrets/sessions/valkey.conf when it differs
# (in place: the running container's single-file bind mount keeps its
# inode), flag the change for sessions_restart_if_changed, fix modes.
sessions_prepare() {
  local d f tmp
  env_require FORWARD_AUTH_REDIS_PASSWORD FORWARD_AUTH_EXT_REDIS_PASSWORD
  d="$(_sessions_dir)"
  f="$d/valkey.conf"
  (umask 077 && mkdir -p "$d")
  tmp="$(umask 077 && mktemp "$d/.valkey.conf.XXXXXX")"
  sessions_conf > "$tmp" || { rm -f "$tmp"; fail "could not render secrets/sessions/valkey.conf"; }
  if ! cmp -s "$tmp" "$f"; then
    [ -e "$f" ] || (umask 077 && : > "$f")
    cat "$tmp" > "$f"
    SESSIONS_CONF_CHANGED=true
    info "Wrote secrets/sessions/valkey.conf (the session store's users)."
  fi
  rm -f "$tmp"
  sessions_fix_perms
}

# sessions_restart_if_changed — before `docker compose up`: a running
# store reads its config only at start, so a changed one (a rotated
# password) needs a restart. It keeps nothing on disk: that signs everyone
# out once.
sessions_restart_if_changed() {
  [ "$SESSIONS_CONF_CHANGED" = true ] || return 0
  [ -n "$(dc ps -q --status running sessions 2>/dev/null)" ] || return 0
  info "Restarting the session store (its users changed; everyone signs in again)..."
  dc restart sessions >/dev/null || fail "could not restart the session store: docker compose logs sessions"
  SESSIONS_CONF_CHANGED=false
}

# sessions_fix_perms — called by secrets_fix_perms (and the above).
sessions_fix_perms() {
  local d
  d="$(_sessions_dir)"
  [ -d "$d" ] || return 0
  chmod 700 "$d"
  ct_group_read "$CT_GID_SESSIONS" "$d/valkey.conf"
}
