# shellcheck shell=bash
#
# `portcullis init | up | down | upgrade` — stack lifecycle.

DNS_PROVIDERS="cloudflare porkbun route53 digitalocean hetzner none"

# _dns_cred_vars <provider> — .env variables holding the provider's credentials.
_dns_cred_vars() {
  case "$1" in
    cloudflare) echo "CLOUDFLARE_API_TOKEN" ;;
    porkbun) echo "PORKBUN_API_KEY PORKBUN_SECRET_API_KEY" ;;
    route53) echo "AWS_ACCESS_KEY_ID AWS_SECRET_ACCESS_KEY AWS_HOSTED_ZONE_ID" ;;
    digitalocean) echo "DO_AUTH_TOKEN" ;;
    hetzner) echo "HETZNER_API_KEY" ;;
    *) echo "" ;;
  esac
}

# _prompt <var> <question> <default> — interactive value unless already set.
_prompt() {
  local var="$1" q="$2" def="$3" reply
  [ -z "${!var:-}" ] || return 0
  if [ "$INIT_INTERACTIVE" = true ]; then
    read -rp "$q [$def]: " reply
    printf -v "$var" '%s' "${reply:-$def}"
  else
    printf -v "$var" '%s' "$def"
  fi
}

# init_write_env <domain> <email> <provider> — create .env (0600) with every
# secret freshly generated. Credentials come from the environment or a
# silent prompt, never from the command line.
init_write_env() {
  local domain="$1" email="$2" provider="$3" file v val creds="" old_umask
  file="$(env_file)"
  for v in $(_dns_cred_vars "$provider"); do
    val="${!v:-}"
    if [ -z "$val" ] && [ "$INIT_INTERACTIVE" = true ]; then
      read -rsp "$v (input hidden): " val
      echo
    fi
    [ -n "$val" ] || warn "$v is empty — set it in .env before ACME can issue certificates."
    case "$val" in *$'\n'*) fail "$v contains a newline" ;; esac
    creds="$creds$v=$val"$'\n'
  done
  old_umask="$(umask)"
  umask 077
  cat > "$file" <<EOF
# Portcullis configuration — generated by ./portcullis init on $(date -u +%Y-%m-%d).
# Holds every secret: keep it 0600 and back it up (./portcullis backup).
# Reference for all settings: .env.example

PORTCULLIS_DOMAIN=$domain
ACME_EMAIL=$email
# Let's Encrypt staging (untrusted certs, no rate limits) — change, then
# run ./portcullis config apply && ./portcullis up
ACME_STAGING=false
MTLS_ENABLED=true

DNS_PROVIDER=$provider
${creds}
KEYCLOAK_ADMIN=admin
LLDAP_BASE_DN=dc=$(printf '%s' "$domain" | sed 's/\./,dc=/g')

# Fixed IPAM for portcullis-proxy; header-auth apps trust only Traefik's IP.
# Change only if it collides with a host network (see .env.example).
PORTCULLIS_PROXY_SUBNET=172.31.250.0/24
PORTCULLIS_PROXY_IP_RANGE=172.31.250.128/25
PORTCULLIS_TRAEFIK_IP=172.31.250.2
# Traefik <-> Keycloak network; Keycloak trusts proxy headers only from
# PORTCULLIS_AUTH_TRAEFIK_IP.
PORTCULLIS_AUTH_SUBNET=172.31.251.0/28
PORTCULLIS_AUTH_IP_RANGE=172.31.251.8/29
PORTCULLIS_AUTH_TRAEFIK_IP=172.31.251.2

# Client certificate lifetime (Vault duration). Revocation is enforced on
# every request, so this is about renewal cadence; see docs/certificates.md.
CLIENT_CERT_TTL=720h

# Off-host backups (restic, docs/backups.md): ./portcullis backup --offsite.
# BACKUP_PASSWORD (generated below) encrypts them. Backups contain the
# Vault root token + unseal key: store BACKUP_PASSWORD OFFLINE as well.
#BACKUP_REPOSITORY=s3:https://s3.amazonaws.com/<bucket>/portcullis
#BACKUP_KEEP_DAILY=7
#BACKUP_KEEP_WEEKLY=4
#BACKUP_KEEP_MONTHLY=6

# Monitoring (docs/monitoring.md): Prometheus, Alertmanager, Grafana at
# https://metrics.<domain> (lldap_admin).
#COMPOSE_PROFILES=monitoring

# Generated secrets
EOF
  chmod 600 "$file"
  umask "$old_umask"
}

init_run() {
  local domain="$1" email="$2" provider="$3" env_only="$4" skip_dns="$5" config_repo="$6" v
  require_cmd openssl
  if [ -f "$(env_file)" ]; then
    info "Using the existing $(env_file)."
    [ -z "$domain$email$provider" ] || warn "--domain/--email/--dns-provider are ignored: .env already exists (edit it instead)."
  else
    [ -n "$domain" ] || domain="${PORTCULLIS_DOMAIN:-}"
    if [ -z "$domain" ]; then
      [ "$INIT_INTERACTIVE" = true ] || usage_error init "--domain is required with --non-interactive (or set PORTCULLIS_DOMAIN)"
      read -rp "Domain (apps live at <name>.<domain>): " domain
    fi
    [[ "$domain" =~ ^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$ ]] || fail "invalid domain: '$domain'"
    [ -n "$email" ] || email="${ACME_EMAIL:-}"
    _prompt email "Email for Let's Encrypt notices" "admin@$domain"
    [[ "$email" =~ ^[^[:space:]]+@[^[:space:]]+$ ]] || fail "invalid email: '$email'"
    [ -n "$provider" ] || provider="${DNS_PROVIDER:-}"
    if [ -z "$provider" ] && [ "$INIT_INTERACTIVE" = true ]; then
      info "DNS provider for the wildcard certificate (ACME DNS-01): $DNS_PROVIDERS,"
      info "or any lego provider name (set its variables in .env yourself)."
    fi
    _prompt provider "DNS provider" cloudflare
    [[ "$provider" =~ ^[a-z0-9_-]+$ ]] || fail "invalid DNS provider: '$provider'"
    init_write_env "$domain" "$email" "$provider"
    ok "Created $(env_file) (0600)."
  fi
  # Any secret that is empty/missing is generated — on a fresh .env that is
  # all of them; on a copied .env.example the blank ones.
  # shellcheck disable=SC2086
  env_generate_missing $CORE_SECRETS $BACKUP_SECRETS
  [ -n "$(env_get KEYCLOAK_ADMIN)" ] || env_set KEYCLOAK_ADMIN admin
  chmod 600 "$(env_file)" 2>/dev/null || true
  env_load
  # shellcheck disable=SC2086
  env_require PORTCULLIS_DOMAIN $CORE_SECRETS

  if [ "$env_only" = true ]; then
    ok ".env is ready. Review it, then run ./portcullis init to set up the stack."
    return 0
  fi

  require_cmd docker jq curl
  docker compose version >/dev/null 2>&1 || fail "the docker compose plugin is required"
  network_check

  if [ "$skip_dns" = true ] || [ "${DNS_PROVIDER:-none}" = none ]; then
    info "Skipping DNS record setup."
  else
    dns_setup false
  fi

  stack_prepare
  info "Initialising Vault..."
  vault_init false
  # forward-auth bind-mounts certs/ca-bundle.crt: it must be a file before
  # the first `up` (rebuilt below once the internal CA exists).
  config_build_ca_bundle

  info "Starting services..."
  dc up -d --build
  wait_healthy 300 vault postgres lldap keycloak

  info "Creating the Vault PKI..."
  pki_setup false true
  config_build_ca_bundle
  # server.key was just written: give Traefik (group 0) read access.
  stack_prepare
  info "Restarting Traefik, forward-auth and Keycloak to pick up the CA chain..."
  dc restart traefik forward-auth keycloak
  wait_healthy 300 keycloak

  keycloak_configure false
  oidc_register

  if [ "$config_repo" = true ]; then
    config_init "" ""
  fi

  local d="$PORTCULLIS_DOMAIN"
  echo ""
  ok "Portcullis is running."
  cat <<EOF

  Enrollment UI   https://enroll.$d
  Directory       https://directory.$d   (LLDAP: admin / LLDAP_ADMIN_PASSWORD in .env)
  Identity        https://auth.$d        (Keycloak: \$KEYCLOAK_ADMIN / KEYCLOAK_ADMIN_PASSWORD in .env)
  Hub             https://hub.$d
  Gateway         https://traefik.$d
  Vault           http://127.0.0.1:8200  (root token: secrets/vault-init.json)

  Next: create users in the directory, then enroll a YubiKey at
  https://enroll.$d (or: ./portcullis cert enroll <user> <email>).
EOF
  warn "Back up secrets/vault-init.json OFFLINE (Vault root token + unseal key)."
}

stack_up() {
  # shellcheck disable=SC2086
  env_require PORTCULLIS_DOMAIN $CORE_SECRETS
  require_cmd docker jq curl
  [ -s "$VAULT_INIT_FILE" ] || fail "Vault was never initialised ($VAULT_INIT_FILE missing). Run ./portcullis init."
  network_check
  stack_prepare
  config_build_ca_bundle
  dc up -d --build
  monitoring_reload
  wait_healthy 300 vault postgres lldap keycloak
  ok "Portcullis is up. Check: ./portcullis status"
}

upgrade_run() {
  local skip_backup="$1"
  require_cmd docker jq curl openssl
  # Only secrets nothing on disk depends on are generated on upgrade; the
  # database / admin passwords must already be there.
  # shellcheck disable=SC2086
  env_generate_missing $ROTATABLE_SECRETS $BACKUP_SECRETS
  # shellcheck disable=SC2086
  env_require PORTCULLIS_DOMAIN $CORE_SECRETS
  [ -s "$VAULT_INIT_FILE" ] || fail "Vault was never initialised ($VAULT_INIT_FILE missing). Run ./portcullis init."
  network_check

  if [ "$skip_backup" = true ]; then
    warn "Skipping the backup (--skip-backup)."
  else
    backup_create
  fi

  info "Pulling images..."
  dc pull --quiet --ignore-buildable 2>/dev/null || dc pull --ignore-buildable

  stack_prepare
  vault_init false
  pki_setup false false
  config_build_ca_bundle

  info "Starting services..."
  dc up -d --build
  monitoring_reload
  if [ "$PKI_CREATED" = true ] || [ "${PKI_TRUSTSTORE_CHANGED:-false}" = true ]; then
    # Traefik, forward-auth and Keycloak read the CA chain only at start-up.
    dc restart traefik forward-auth keycloak >/dev/null
  fi
  wait_healthy 300 vault postgres lldap keycloak
  keycloak_configure false
  oidc_register
  # Picks up a FORWARD_AUTH_CLIENT_SECRET generated above, if any.
  dc up -d forward-auth >/dev/null

  ok "Upgrade complete.${BACKUP_LAST_DIR:+ Backup: $BACKUP_LAST_DIR}"
  echo "    Verify: ./portcullis status"
}

help_init() {
  cat <<'EOF'
Usage: portcullis init [options]

First-time setup. Creates .env (0600) with every secret randomly generated
(Postgres, Keycloak admin, LLDAP admin + JWT, forward-auth client + cookie
secret, HUB_PROXY_SECRET, BACKUP_PASSWORD for off-host backups), then: DNS records, Vault init + unseal + enroll
AppRole, CA bundle, `docker compose up`, Vault PKI (incl. a self-signed
wildcard server cert for local use), Keycloak realm, OIDC clients, config/.

With an existing .env it is kept; only empty/missing secrets are generated.
Every step is idempotent, so init can be re-run after a failure.

Options:
  --domain DOMAIN         base domain (default: $PORTCULLIS_DOMAIN or prompt)
  --email EMAIL           Let's Encrypt account email (default: admin@DOMAIN)
  --dns-provider NAME     cloudflare|porkbun|route53|digitalocean|hetzner|none
                          or another lego provider name (default: cloudflare)
  --non-interactive       never prompt; DNS credentials must be in the
                          environment (e.g. CLOUDFLARE_API_TOKEN=...)
  --env-only              only write/complete .env, then stop
  --skip-dns              do not create DNS records
  --no-config-repo        do not create the config/ git repo

DNS provider credentials are read from the environment or a hidden prompt,
never from the command line.
EOF
}

help_up() {
  cat <<'EOF'
Usage: portcullis up

Start (or update) the core stack: checks .env and the portcullis-proxy
network settings, creates bind-mount sources, rebuilds certs/ca-bundle.crt,
runs `docker compose up -d --build` and waits for vault, postgres, lldap
and keycloak to be healthy. Vault unseals itself on start.
EOF
}

help_down() {
  cat <<'EOF'
Usage: portcullis down

Stop and remove the core containers (`docker compose down`). Volumes and
secrets/ are kept; apps enabled in the Hub run as their own projects and
are not touched.
EOF
}

help_upgrade() {
  cat <<'EOF'
Usage: portcullis upgrade [--skip-backup]

Update a running installation after `git pull`:
  1. generates any missing HUB_PROXY_SECRET / FORWARD_AUTH_* / LLDAP_JWT_SECRET
     / BACKUP_PASSWORD (other secrets must already be in .env)
  2. creates a local backup (portcullis backup: Vault snapshot, pg_dump,
     volumes, .env, certs/, secrets/)
  3. pulls images
  4. re-runs the idempotent setup steps: vault init, pki setup (client
     role incl. CLIENT_CERT_TTL, Keycloak truststore), CA bundle
  5. docker compose up -d --build, waits for health
  6. keycloak configure, oidc register

Options:
  --skip-backup   do not create a backup first
EOF
}

cmd_init() {
  local domain="" email="" provider="" env_only=false skip_dns=false config_repo=true
  INIT_INTERACTIVE=true
  [ -t 0 ] || INIT_INTERACTIVE=false
  while [ $# -gt 0 ]; do
    case "$1" in
      --domain) need_value init "$1" "${2:-}"; domain="$2"; shift ;;
      --email) need_value init "$1" "${2:-}"; email="$2"; shift ;;
      --dns-provider) need_value init "$1" "${2:-}"; provider="$2"; shift ;;
      --non-interactive) INIT_INTERACTIVE=false ;;
      --env-only) env_only=true ;;
      --skip-dns) skip_dns=true ;;
      --no-config-repo) config_repo=false ;;
      -h|--help) help_init; return 0 ;;
      *) usage_error init "unknown argument: $1" ;;
    esac
    shift
  done
  init_run "$domain" "$email" "$provider" "$env_only" "$skip_dns" "$config_repo"
}

cmd_up() {
  while [ $# -gt 0 ]; do
    case "$1" in
      -h|--help) help_up; return 0 ;;
      *) usage_error up "unknown argument: $1" ;;
    esac
  done
  need_env
  stack_up
}

cmd_down() {
  while [ $# -gt 0 ]; do
    case "$1" in
      -h|--help) help_down; return 0 ;;
      *) usage_error down "unknown argument: $1" ;;
    esac
  done
  need_env
  require_cmd docker
  dc down
}

cmd_upgrade() {
  local skip_backup=false
  while [ $# -gt 0 ]; do
    case "$1" in
      --skip-backup) skip_backup=true ;;
      -h|--help) help_upgrade; return 0 ;;
      *) usage_error upgrade "unknown argument: $1" ;;
    esac
    shift
  done
  need_env
  upgrade_run "$skip_backup"
}
