# shellcheck shell=bash
#
# `portcullis worker …` — a worker server (multiple servers, contract
# §17.7): this checkout runs only the agent and its socket proxy
# (docker-compose.worker.yml, project portcullis-worker), joined to a
# primary with a join code from its Hub (Settings → Servers).
#
#   worker join [--runtime docker|podman] [--force]   (the code on stdin)
#   worker status [--json]
#   worker upgrade
#   worker leave [--yes]
#   worker stop|start <instance>
#
# The join code is a secret: it is read from stdin (or a no-echo prompt),
# kept in a shell variable and handed to `portcullis-agent join` on its
# stdin only; never an argument, a file the CLI writes, or a log line.

WORKER_JOIN_WAIT="${WORKER_JOIN_WAIT:-300}"
WORKER_DEFAULT_ROOTS="/srv:/mnt:/media"
WORKER_CODE_MAX=4096
# The agent's own compose project (docker-compose.worker.yml name:).
WORKER_PROJECT=portcullis-worker
# The copy for a code on the command line (contract §17.7).
WORKER_CODE_ARGV_MSG="the join code is a secret: paste it when asked, or pipe it in"

# worker_role — this host's role from .env: worker, or primary (an .env
# without PORTCULLIS_ROLE is a primary, ruling P37); "" without an .env.
worker_role() {
  [ -f "$(env_file)" ] || return 0
  case "$(env_get PORTCULLIS_ROLE 2>/dev/null)" in
    worker) echo worker ;;
    *) echo primary ;;
  esac
}

# worker_role_guard <cmd> — on a worker every command but worker, help,
# version and status refuses (contract §17.7).
worker_role_guard() {
  local a
  case "$1" in worker|help|version|status|-h|--help|"") return 0 ;; esac
  # --help never needs .env (and never refuses).
  for a in "$@"; do case "$a" in -h|--help) return 0 ;; esac; done
  [ "$(worker_role)" != worker ] || fail "this host is a Portcullis worker: use ./portcullis worker …"
}

_worker_data() { printf '%s/worker-data' "$PORTCULLIS_ROOT"; }
_worker_roots_file() { printf '%s/docker-compose.worker.roots.yml' "$PORTCULLIS_ROOT"; }

# worker_compose_files — COMPOSE_FILE on a worker (runtime_export): the
# worker file, its generated folder-root binds and, under rootless Podman,
# the worker overlays (never the core ones: they name core services).
worker_compose_files() {
  local files
  files="$PORTCULLIS_HOME/docker-compose.worker.yml:$(_worker_roots_file)"
  # The operator's own override (e.g. extra_hosts for the primary's name).
  [ ! -f "$PORTCULLIS_ROOT/docker-compose.worker.override.yml" ] || files="$files:$PORTCULLIS_ROOT/docker-compose.worker.override.yml"
  if _rt_is_podman; then
    files="$files:$PORTCULLIS_HOME/docker-compose.worker.podman.yml"
    if _rt_selinux_enforcing; then files="$files:$PORTCULLIS_HOME/docker-compose.worker.podman-selinux.yml"; fi
  fi
  printf '%s' "$files"
}

# _worker_roots <colon list> — the folder roots, one per line, each an
# absolute clean path other than / (as the agent's AGENT_BIND_ROOTS).
_worker_roots() {
  local r
  local -a rs
  IFS=: read -r -a rs <<< "${1:-$WORKER_DEFAULT_ROOTS}"
  for r in "${rs[@]}"; do
    [[ "$r" =~ ^(/[A-Za-z0-9._-]+)+$ ]] && [ "$r" != / ] && [[ "$r" != */. ]] && [[ "$r" != */.. ]] && [[ "$r" != */./* ]] && [[ "$r" != */../* ]] \
      || fail "PORTCULLIS_WORKER_BIND_ROOTS: '$r' must be an absolute clean path other than /"
    printf '%s\n' "$r"
  done
}

# _worker_inside <path> <dir> — path is dir or below it.
_worker_inside() { [ "$1" = "$2" ] || [ "${1#"$2"/}" != "$1" ]; }

# worker_check_roots — every folder root is an existing directory (the
# agent refuses to start otherwise; compose would make a missing one
# root-owned), and neither this install nor its worker-data lies inside one.
worker_check_roots() {
  local r
  # The agent (uid 10008) sees this install at the same path and must
  # traverse it: its image's /root is 0700.
  ! _worker_inside "$PORTCULLIS_ROOT" /root || fail "this install ($PORTCULLIS_ROOT) is under /root, which the agent (uid 10008) can't traverse: put the checkout elsewhere (e.g. /opt/portcullis)"
  while IFS= read -r r; do
    [ -d "$r" ] && [ ! -L "$r" ] || fail "the folder root $r doesn't exist (or is a link): create it, or set PORTCULLIS_WORKER_BIND_ROOTS in .env"
    ! _worker_inside "$PORTCULLIS_ROOT" "$r" || fail "this install ($PORTCULLIS_ROOT) is inside the folder root $r: move it out, or narrow PORTCULLIS_WORKER_BIND_ROOTS"
  done < <(_worker_roots "${PORTCULLIS_WORKER_BIND_ROOTS:-}")
}

# worker_roots_write — docker-compose.worker.roots.yml: every folder root
# bound read-only into the agent at the same path (never relabelled).
worker_roots_write() {
  local r f
  f="$(_worker_roots_file)"
  {
    echo "# Generated by ./portcullis worker from PORTCULLIS_WORKER_BIND_ROOTS. Do not edit."
    echo "services:"
    echo "  agent:"
    echo "    volumes:"
    while IFS= read -r r; do
      printf '      - {type: bind, source: %s, target: %s, read_only: true}\n' "$r" "$r"
    done < <(_worker_roots "${PORTCULLIS_WORKER_BIND_ROOTS:-}")
  } > "$f.tmp"
  mv "$f.tmp" "$f"
}

# _worker_engine_root — the engine's data root (DockerRootDir), as the
# agent reads it: mounted read-only into the agent at the same path.
_worker_engine_root() {
  local d
  _rt_docker_only
  d="$(docker info --format '{{.DockerRootDir}}' 2>/dev/null)" || fail "the engine doesn't say its data root (docker info)"
  [[ "$d" =~ ^/[^[:space:]]*$ ]] && [ "$d" != / ] || fail "the engine's data root '$d' isn't an absolute path"
  printf '%s' "$d"
}

# _worker_host_env — the host facts the agent reads from .env, rewritten by
# join and upgrade: the engine root, the unprivileged port start.
_worker_host_env() {
  local root ps
  root="$(_worker_engine_root)" || exit 1
  ps="$(runtime_port_start)"
  [[ "$ps" =~ ^[0-9]+$ ]] || ps=1024
  _worker_set PORTCULLIS_WORKER_ENGINE_ROOT "$root"
  _worker_set AGENT_UNPRIVILEGED_PORT_START "$ps"
}

_worker_set() { env_set "$1" "$2"; export "$1=$2"; }

# _worker_agent <args> — `portcullis-agent <args>` in the running agent.
_worker_agent() { _rt_docker_only; dc exec -T agent portcullis-agent "$@"; }

# _worker_state — the agent's identity state (none|enrolling|ready|refused), or "".
_worker_state() {
  _worker_agent status 2>/dev/null | jq -r '.state // empty' 2>/dev/null || true
}

# _worker_read_code — the join code from stdin, or a no-echo prompt on a
# terminal, into WORKER_CODE (never echoed). Trailing whitespace dropped.
_worker_read_code() {
  WORKER_CODE=""
  if [ -t 0 ]; then
    IFS= read -rs -p "Join code (from the Hub, Settings → Servers; input hidden): " WORKER_CODE || true
    echo >&2
  else
    WORKER_CODE="$(head -c $((WORKER_CODE_MAX + 1)))" || true
  fi
  WORKER_CODE="${WORKER_CODE%"${WORKER_CODE##*[![:space:]]}"}"
  WORKER_CODE="${WORKER_CODE#"${WORKER_CODE%%[![:space:]]*}"}"
  [ -n "$WORKER_CODE" ] || fail "no join code on stdin: paste it when asked, or pipe it in"
  [ "${#WORKER_CODE}" -le "$WORKER_CODE_MAX" ] || { WORKER_CODE=""; fail "the join code must be at most 4 KiB"; }
  case "$WORKER_CODE" in
    pcj1.*) ;;
    *) WORKER_CODE=""; fail "that isn't a join code (it starts with pcj1.): copy it again from the Hub" ;;
  esac
  case "$WORKER_CODE" in *[!A-Za-z0-9._-]*) WORKER_CODE=""; fail "that isn't a join code: copy it again from the Hub" ;; esac
}

worker_join() {
  local runtime="$1" force="$2" role data st last="" start
  _rt_docker_only
  role="$(worker_role)"
  [ "$role" != primary ] || fail "this host is a Portcullis primary (.env): a worker needs a host (or a checkout) of its own"
  data="$(_worker_data)"
  if [ -d "$data/identity" ] && [ -n "$(ls -A "$data/identity" 2>/dev/null)" ] && [ "$force" != true ]; then
    fail "this worker already has an identity: ./portcullis worker leave first, or pass --force to join again"
  fi
  # The code first: nothing is written for a refused one.
  _worker_read_code
  runtime="$(runtime_detect "$runtime")" || { WORKER_CODE=""; exit 1; }
  [ "$runtime" != kubernetes ] || { WORKER_CODE=""; fail "Kubernetes workers aren't supported: a worker runs Docker or rootless Podman"; }
  # Every check before anything is written.
  export PORTCULLIS_ROLE=worker CONTAINER_RUNTIME="$runtime"
  export PORTCULLIS_WORKER_BIND_ROOTS="${PORTCULLIS_WORKER_BIND_ROOTS:-$WORKER_DEFAULT_ROOTS}"
  if [ "$runtime" = podman ]; then export PORTCULLIS_ENGINE_SOCKET; PORTCULLIS_ENGINE_SOCKET="$(runtime_podman_socket)"; fi
  _RT_CHECKED="" runtime_check
  runtime_require_host
  worker_check_roots
  info "Writing .env (a $runtime worker)..."
  [ -f "$(env_file)" ] || (umask 077 && : > "$(env_file)")
  chmod 600 "$(env_file)"
  _worker_set PORTCULLIS_ROLE worker
  _worker_set CONTAINER_RUNTIME "$runtime"
  if [ "$runtime" = podman ]; then _worker_set PORTCULLIS_ENGINE_SOCKET "$PORTCULLIS_ENGINE_SOCKET"; fi
  _worker_set PORTCULLIS_WORKER_DATA "$data"
  _worker_set PORTCULLIS_WORKER_INSTALL "$PORTCULLIS_ROOT"
  _worker_set PORTCULLIS_WORKER_BIND_ROOTS "$PORTCULLIS_WORKER_BIND_ROOTS"
  _worker_host_env
  worker_roots_write
  (umask 027 && mkdir -p "$data")
  # 0751: the apps' own users traverse to their template files (the
  # agent's files/ tree, 0755 dirs as the primary's templates/); the agent's
  # identity, bundles and resolved models stay 0700 inside.
  chmod 751 "$data"
  ct_own "$CT_UID_AGENT:$CT_UID_HUB" "$data"
  # Images: compose run / up pull the missing ones (worker upgrade pulls).
  if [ "$force" = true ]; then
    dc stop agent >/dev/null 2>&1 || true
  fi
  info "Handing the join code to the agent..."
  printf '%s' "$WORKER_CODE" | dc run --rm --no-deps -T --entrypoint portcullis-agent agent join \
    || { WORKER_CODE=""; fail "the agent refused the join code (see above): ask the Hub for a new one"; }
  WORKER_CODE=""
  info "Starting the agent..."
  # shellcheck disable=SC2046  # nothing or --no-build
  dc up -d $(runtime_no_build) || fail "could not start the agent (docker compose logs agent)"
  info "Waiting up to ${WORKER_JOIN_WAIT}s for the primary to enrol this worker..."
  start=$SECONDS
  while :; do
    st="$(_worker_state)"
    if [ -n "$st" ] && [ "$st" != "$last" ] && ! { [ "$st" = ready ] && [ "$last" = "ready (containers starting)" ]; }; then info "agent: $st"; last="$st"; fi
    case "$st" in
      ready)
        # Enrolled: ready once its containers are healthy too (worker status's
        # rule), else `worker status` right after join would still fail.
        if [ "$(worker_status_json | jq -r .problem)" = false ]; then
          ok "This worker is ready (./portcullis worker status). Place apps on it in the Hub."; return 0
        fi
        [ "$last" = "ready (containers starting)" ] || { info "agent: waiting for the containers' health checks"; last="ready (containers starting)"; st="$last"; } ;;
      refused) fail "the primary refused the enrolment: ask the Hub for a new code, then ./portcullis worker join --force" ;;
    esac
    if [ $((SECONDS - start)) -ge "$WORKER_JOIN_WAIT" ]; then
      # The agent's last lines (it never logs the code or a key).
      dc logs --no-color --tail=15 agent >&2 2>/dev/null || true
      [ "$st" != "ready (containers starting)" ] || fail "enrolled, but its containers aren't healthy after ${WORKER_JOIN_WAIT}s: ./portcullis worker status"
      fail "not ready after ${WORKER_JOIN_WAIT}s (state: ${st:-unknown}): check the Hub's Servers page and ./portcullis worker status"
    fi
    sleep 3
  done
}

# worker_status_json — {role, runtime, agent{state, server_id, tunnel_ip},
# services[{service, state, health}], problem}.
worker_status_json() {
  local st ps
  _rt_docker_only
  st="$(_worker_agent status 2>/dev/null)" || st=""
  ps="$(dc ps -a --format json 2>/dev/null)" || ps=""
  jq -n --arg rt "${CONTAINER_RUNTIME:-}" --arg st "$st" --arg ps "$ps" '
    ($st | try fromjson catch null) as $a
    | ([$ps | split("\n")[] | select(. != "") | (try fromjson catch empty)] | flatten) as $p
    | {role: "worker", runtime: $rt,
       agent: (if $a == null then null else {state: $a.state, server_id: $a.server_id, tunnel_ip: $a.tunnel_ip} end),
       services: [$p[] | {service: .Service, state: .State, health: (.Health // "")}]}
    | .problem = (.agent == null or .agent.state != "ready"
        or ([.services[] | select(.state != "running" or (.health != "" and .health != "healthy"))] | length > 0)
        or ([.services[].service] | (index("agent") == null or index("socket-proxy-agent") == null)))'
}

worker_status() {
  local j
  j="$(worker_status_json)"
  if [ "$1" = true ]; then printf '%s\n' "$j"
  else
    printf '%sWorker%s\n' "$C_CYAN" "$C_NC"
    while IFS=$'\t' read -r s text; do [ -n "$s" ] && _st_line "$s" "$text"; done < <(printf '%s' "$j" | jq -r '
      (if .agent == null then ["fail", "the agent doesn'"'"'t answer (docker compose logs agent)"]
       elif .agent.state == "ready" then ["ok", "server \(.agent.server_id) (\(.agent.tunnel_ip)): ready"]
       else ["fail", "agent: \(.agent.state)" + (if .agent.server_id then " (server \(.agent.server_id))" else "" end)] end),
      (.services[] | [(if .state == "running" and (.health == "" or .health == "healthy") then "ok" else "fail" end),
         "\(.service): \(.state)" + (if .health != "" then " (\(.health))" else "" end)])
      | @tsv')
  fi
  [ "$(printf '%s' "$j" | jq -r .problem)" != true ]
}

worker_upgrade() {
  _rt_docker_only
  worker_check_roots
  _worker_host_env
  worker_roots_write
  info "Pulling the agent's images..."
  dc pull --quiet || fail "could not pull the worker's images"
  # shellcheck disable=SC2046  # nothing or --no-build
  dc up -d $(runtime_no_build) || fail "could not start the agent (docker compose logs agent)"
  ok "The worker is up to date (./portcullis worker status)."
}

# _worker_projects — the app instances on this engine: the compose
# projects portcullis-<id> with a valid id (the agent's own scope rule),
# never the agent's own project. Read from the engine's labels, never from
# worker-data/projects (0700, the agent's uid: a non-root operator or a
# rootless Podman user can't list it). Fails when the engine doesn't answer.
_worker_projects() {
  local out p id
  _rt_docker_only
  out="$(docker ps -a --format '{{.Label "com.docker.compose.project"}}')" || return 1
  while IFS= read -r p; do
    id="${p#portcullis-}"
    if [ "$id" != "$p" ] && [ "$p" != "$WORKER_PROJECT" ] && [[ "$id" =~ ^[a-z][a-z0-9-]{0,30}$ ]]; then
      printf '%s\n' "$id"
    fi
  done < <(printf '%s\n' "$out" | sort -u)
}

# _worker_compose_p <instance> <args> — `docker compose -p portcullis-<id>`
# from / (no project files read: stop / start / down by name only).
_worker_compose_p() {
  local id="$1"
  _rt_docker_only
  shift
  (cd / && docker compose -p "portcullis-$id" "$@")
}

# _worker_wipe <dir> — remove worker-data (owned by the agent's uid).
_worker_wipe() {
  local d="$1"
  _rt_docker_only
  [ -d "$d" ] || return 0
  if _rt_is_podman; then
    podman unshare rm -rf -- "$d" || fail "could not remove $d (try: podman unshare rm -rf '$d')"
    return 0
  fi
  if [ "$(id -u)" = 0 ]; then rm -rf -- "$d"; return 0; fi
  # shellcheck disable=SC2016  # expanded by the helper's sh
  docker run --rm --network none --user 0:0 --cap-drop ALL --cap-add DAC_OVERRIDE --cap-add FOWNER \
    --security-opt no-new-privileges:true --mount "type=bind,src=$d,dst=/w" "$PORTCULLIS_HELPER_IMAGE" \
    sh -c 'find /w -mindepth 1 -delete' >/dev/null || fail "could not empty $d"
  rmdir -- "$d" || fail "could not remove $d"
}

# _worker_none_left <what stays> — fail while any app container is here.
_worker_none_left() {
  local left
  left="$(_worker_projects)" || fail "the engine doesn't list its containers: $1"
  [ -z "$left" ] || fail "app containers are still here ($(printf '%s' "$left" | sed 's/^/portcullis-/' | tr '\n' ' ' | sed 's/ $//')): $1; take them down (docker compose -p portcullis-<id> down) and run ./portcullis worker leave again"
}

worker_leave() {
  local yes="$1" id ans sid projects
  _rt_docker_only
  sid="$(_worker_agent status 2>/dev/null | jq -r '.server_id // empty' 2>/dev/null || true)"
  if [ "$yes" != true ]; then
    [ -t 0 ] || usage_error "worker leave" "no terminal to confirm on: pass --yes"
    printf 'This takes the apps placed here down (their volumes stay), wipes this worker'"'"'s identity and removes %s.\nThe primary still lists it: remove or revoke it in the Hub (Settings → Servers).\nType leave to go on: ' "$(_worker_data)" >&2
    IFS= read -r ans || true
    [ "$ans" = leave ] || fail "not confirmed: nothing changed"
  fi
  projects="$(_worker_projects)" || fail "the engine doesn't list its containers: nothing changed"
  for id in $projects; do
    info "Taking portcullis-$id down (volumes kept)..."
    _worker_compose_p "$id" down || warn "could not take portcullis-$id down"
  done
  # Never a leave with apps still here: the identity and worker-data stay
  # until every app container is gone (run leave again).
  _worker_none_left "the identity and worker-data are kept"
  _worker_agent leave >/dev/null 2>&1 || warn "the agent didn't answer: its identity goes with worker-data"
  info "Stopping the agent..."
  dc down -v || fail "could not take the worker down (docker compose logs agent)"
  _worker_none_left "worker-data is kept"
  _worker_wipe "$(_worker_data)"
  ok "This host left${sid:+ as $sid}. Remove the server in the Hub; ./portcullis worker join to join again."
}

worker_stop_start() {
  local verb="$1" id="$2" projects
  projects="$(_worker_projects)" || fail "the engine doesn't list its containers"
  printf '%s\n' "$projects" | grep -qx -- "$id" || fail "no app instance $id on this worker"
  if [ "$verb" = stop ]; then
    warn "break-glass: the primary still routes $id here; its users get errors until it runs again (the Hub shows it as stopped)"
  fi
  _worker_compose_p "$id" "$verb" || fail "docker compose $verb of portcullis-$id failed"
  ok "portcullis-$id: $verb done."
}

