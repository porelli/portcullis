}

cmd_worker() {
  local sub="${1:-}"
  [ $# -gt 0 ] && shift
  case "$sub" in
    ""|-h|--help|help) help_worker; [ -n "$sub" ] || exit 2; return 0 ;;
    join|status|upgrade|leave|stop|start) ;;
    *) usage_error worker "unknown subcommand: $sub" ;;
  esac
  local fn="help_worker_${sub}" runtime="" force=false json=false yes=false
  local -a pos=()
  while [ $# -gt 0 ]; do
    case "$sub:$1" in
      *:-h|*:--help) "$fn"; return 0 ;;
      join:--runtime) need_value "worker join" "$1" "${2:-}"; runtime="$2"; shift ;;
      join:--force) force=true ;;
      status:--json) json=true ;;
      leave:--yes) yes=true ;;
      join:-*|*:-*) usage_error "worker $sub" "unknown option: $1" ;;
      *) pos+=("$1") ;;
    esac
    shift
  done
  case "$sub" in
    join)
      if [ "${#pos[@]}" -gt 0 ]; then printf 'portcullis worker join: %s\n' "$WORKER_CODE_ARGV_MSG" >&2; exit 2; fi
      case "$runtime" in ""|docker|podman) ;; kubernetes) usage_error "worker join" "Kubernetes workers aren't supported: --runtime must be docker or podman" ;; *) usage_error "worker join" "--runtime must be docker or podman" ;; esac ;;
    stop|start)
      [ "${#pos[@]}" -eq 1 ] || usage_error "worker $sub" "expected exactly one <instance>"
      [[ "${pos[0]}" =~ ^[a-z][a-z0-9-]{0,30}$ ]] || usage_error "worker $sub" "invalid instance id: ${pos[0]}" ;;
    *) [ "${#pos[@]}" -eq 0 ] || usage_error "worker $sub" "unexpected argument: ${pos[0]}" ;;
  esac
  # The worker's commands only (need_env refuses the core ones here).
  export _PORTCULLIS_WORKER_CMD=1
  if [ "$sub" = join ]; then
    if [ -f "$(env_file)" ]; then env_load; fi
    case "${runtime:-${CONTAINER_RUNTIME:-}}" in kubernetes) fail "Kubernetes workers aren't supported: a worker runs Docker or rootless Podman" ;; esac
    worker_join "$runtime" "$force"
    return
  fi
  [ "$(worker_role)" = worker ] || fail "this host isn't a Portcullis worker: ./portcullis worker join first"
  need_env
  case "$sub" in
    status) worker_status "$json" ;;
    upgrade) worker_upgrade ;;
    leave) worker_leave "$yes" ;;
    stop|start) worker_stop_start "$sub" "${pos[0]}" ;;
  esac
}
