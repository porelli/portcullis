help_worker() {
  cat <<'EOF'
Usage: portcullis worker <subcommand>

  join          Join this host to a primary as a worker server (the code on stdin)
  status        The agent's state and its containers
  upgrade       Pull the agent's images and restart it
  leave         Take this worker's apps down and wipe its identity
  stop          Stop one app instance here (break-glass)
  start         Start one app instance here again

Run 'portcullis worker <subcommand> --help' for details.
EOF
}

help_worker_join() {
  cat <<'EOF'
Usage: portcullis worker join [--runtime docker|podman] [--force]

Join this host to a primary as a worker server (contract §17.7). Get a join
code in the primary's Hub (Settings → Servers → Add server), then paste it
when asked, or pipe it in:

  ./portcullis worker join < code.txt

The code is a secret and valid for 15 minutes, once: it is never accepted
as an argument. join writes .env (PORTCULLIS_ROLE=worker, the runtime,
PORTCULLIS_WORKER_DATA = this checkout's worker-data/), starts the agent and
its socket proxy (project portcullis-worker) and waits up to 5 minutes for
the primary to enrol it. The worker needs no inbound port: it dials out to
the primary's link port (UDP).

Refused on a primary, on Kubernetes, and when this worker already has an
identity (pass --force to join again). Folder roots: PORTCULLIS_WORKER_BIND_ROOTS
(default /srv:/mnt:/media), each must exist.

Options:
  --runtime docker|podman  the container runtime (default: Docker if its
                           engine answers, else rootless Podman)
  --force                  join again over an existing identity
EOF
}

help_worker_status() {
  cat <<'EOF'
Usage: portcullis worker status [--json]

The agent's state (enrolling, ready, …), its server id and tunnel address,
and the worker's containers. Exit 1 unless the agent is ready and healthy.
EOF
}

help_worker_upgrade() {
  cat <<'EOF'
Usage: portcullis worker upgrade

Pull the agent's images (AGENT_IMAGE) and restart it; the folder-root binds
and the host facts the agent reads are written again.
EOF
}

help_worker_leave() {
  cat <<'EOF'
Usage: portcullis worker leave [--yes]

Take every app instance placed here down (their volumes stay), wipe the
worker's identity, take the agent down and remove worker-data/ (after a
typed confirmation; --yes skips it). Remove or revoke the server in the
primary's Hub too.
EOF
}

help_worker_stop() {
  cat <<'EOF'
Usage: portcullis worker stop <instance>

Break-glass: stop one app instance on this worker (docker compose -p
portcullis-<instance> stop). The primary keeps routing to it.
EOF
}

help_worker_start() {
  cat <<'EOF'
Usage: portcullis worker start <instance>

Start an app instance stopped with ./portcullis worker stop.
